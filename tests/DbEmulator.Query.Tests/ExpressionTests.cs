namespace DbEmulator.Query.Tests;

public class ExpressionTests
{
    [Theory]
    [InlineData("true AND true", "true")]
    [InlineData("true AND false", "false")]
    [InlineData("true AND undefined", "undefined")]
    [InlineData("false AND undefined", "false")]
    [InlineData("undefined AND false", "false")]
    [InlineData("1 AND true", "undefined")]
    [InlineData("false AND 1", "false")]
    [InlineData("'a' AND 'b'", "undefined")]
    [InlineData("true OR undefined", "true")]
    [InlineData("undefined OR true", "true")]
    [InlineData("false OR undefined", "undefined")]
    [InlineData("false OR false", "false")]
    [InlineData("true OR 1", "true")]
    [InlineData("null OR false", "undefined")]
    [InlineData("NOT true", "false")]
    [InlineData("NOT false", "true")]
    [InlineData("NOT undefined", "undefined")]
    [InlineData("NOT 1", "undefined")]
    [InlineData("NOT null", "undefined")]
    [InlineData("NOT NOT true", "true")]
    public void ThreeValuedLogic(string expression, string expected) => Assert.Equal(expected, T.Eval(expression));

    [Theory]
    [InlineData("1 = 1", "true")]
    [InlineData("1 = 1.0", "true")]
    [InlineData("1 = '1'", "false")]
    [InlineData("'a' = 'a'", "true")]
    [InlineData("'a' = 'A'", "false")]
    [InlineData("null = null", "true")]
    [InlineData("null = false", "false")]
    [InlineData("true = true", "true")]
    [InlineData("[1,2] = [1,2]", "true")]
    [InlineData("[1,2] = [2,1]", "false")]
    [InlineData("[1,[2,'x']] = [1.0,[2,'x']]", "true")]
    [InlineData("{'a':1,'b':2} = {'b':2,'a':1}", "true")]
    [InlineData("{'a':1} = {'a':1,'b':2}", "false")]
    [InlineData("{} = {}", "true")]
    [InlineData("[] = {}", "false")]
    [InlineData("undefined = undefined", "undefined")]
    [InlineData("1 = undefined", "undefined")]
    [InlineData("1 != '1'", "true")]
    [InlineData("1 <> 2", "true")]
    [InlineData("1 != 1", "false")]
    [InlineData("null != null", "false")]
    [InlineData("1 != undefined", "undefined")]
    public void Equality(string expression, string expected) => Assert.Equal(expected, T.Eval(expression));

    [Theory]
    [InlineData("1 < 2", "true")]
    [InlineData("2 <= 2", "true")]
    [InlineData("3 > 2.5", "true")]
    [InlineData("2 >= 3", "false")]
    [InlineData("'a' < 'b'", "true")]
    [InlineData("'B' < 'a'", "true")]
    [InlineData("'abc' > 'ab'", "true")]
    [InlineData("1 < '2'", "undefined")]
    [InlineData("'1' > 0", "undefined")]
    [InlineData("null <= null", "true")]
    [InlineData("null >= null", "true")]
    [InlineData("null < null", "false")]
    [InlineData("null < 1", "undefined")]
    [InlineData("false < true", "true")]
    [InlineData("true <= false", "false")]
    [InlineData("[1] < [2]", "undefined")]
    [InlineData("{} < {}", "undefined")]
    [InlineData("undefined < 1", "undefined")]
    public void Comparisons(string expression, string expected) => Assert.Equal(expected, T.Eval(expression));

    [Theory]
    [InlineData("1 IN (1, 2)", "true")]
    [InlineData("3 IN (1, 2)", "false")]
    [InlineData("'1' IN (1, 2)", "false")]
    [InlineData("undefined IN (1)", "undefined")]
    [InlineData("1 IN (undefined, 1)", "true")]
    [InlineData("null IN (null)", "true")]
    [InlineData("[1] IN ([1], 2)", "true")]
    [InlineData("3 NOT IN (1, 2)", "true")]
    [InlineData("1 NOT IN (1, 2)", "false")]
    [InlineData("7 IN (1, 2, 3, 4, 5, 6, 7)", "true")]
    [InlineData("8 IN (1, 2, 3, 4, 5, 6, 7)", "false")]
    [InlineData("5 BETWEEN 1 AND 10", "true")]
    [InlineData("1 BETWEEN 1 AND 1", "true")]
    [InlineData("11 BETWEEN 1 AND 10", "false")]
    [InlineData("5 NOT BETWEEN 1 AND 10", "false")]
    [InlineData("'b' BETWEEN 'a' AND 'c'", "true")]
    [InlineData("5 BETWEEN 1 AND 'z'", "undefined")]
    [InlineData("50 BETWEEN 1 AND 'z'", "undefined")]
    [InlineData("0 BETWEEN 1 AND 'z'", "false")]
    [InlineData("undefined BETWEEN 1 AND 2", "undefined")]
    [InlineData("1 + 1 BETWEEN 1 AND 3 - 1", "true")]
    public void InAndBetween(string expression, string expected) => Assert.Equal(expected, T.Eval(expression));

    [Theory]
    [InlineData("'abc' LIKE 'a%'", "true")]
    [InlineData("'abc' LIKE 'A%'", "false")]
    [InlineData("'abc' LIKE '%c'", "true")]
    [InlineData("'abc' LIKE '%b%'", "true")]
    [InlineData("'abc' LIKE '_b_'", "true")]
    [InlineData("'abc' LIKE '__'", "false")]
    [InlineData("'abc' LIKE 'ab'", "false")]
    [InlineData("'abc' LIKE 'abc'", "true")]
    [InlineData("'' LIKE '%'", "true")]
    [InlineData("'a%c' LIKE 'a!%c' ESCAPE '!'", "true")]
    [InlineData("'abc' LIKE 'a!%c' ESCAPE '!'", "false")]
    [InlineData("'a_c' LIKE 'a\\\\_c' ESCAPE '\\\\'", "true")]
    [InlineData("'b' LIKE '[a-c]'", "true")]
    [InlineData("'d' LIKE '[a-c]'", "false")]
    [InlineData("'d' LIKE '[^a-c]'", "true")]
    [InlineData("'x1' LIKE '[xyz][0-9]'", "true")]
    [InlineData("'aXbXc' LIKE '%X%X%'", "true")]
    [InlineData("'mississippi' LIKE '%iss%ppi'", "true")]
    [InlineData("'abc' NOT LIKE 'x%'", "true")]
    [InlineData("'abc' NOT LIKE 'a%'", "false")]
    [InlineData("1 LIKE '1'", "undefined")]
    [InlineData("'1' LIKE 1", "undefined")]
    [InlineData("undefined NOT LIKE 'a'", "undefined")]
    public void Like(string expression, string expected) => Assert.Equal(expected, T.Eval(expression));

    [Fact]
    public void LikeWithParameterPattern() =>
        Assert.Equal(T.J("['3','6','8','9']"), T.Run("SELECT VALUE c.id FROM c WHERE c.name LIKE @p", """{"@p":"%a%"}"""));

    [Theory]
    [InlineData("1 + 2", "3")]
    [InlineData("10 - 2.5", "7.5")]
    [InlineData("2 * 3.5", "7")]
    [InlineData("10 / 4", "2.5")]
    [InlineData("7 % 3", "1")]
    [InlineData("-7 % 3", "-1")]
    [InlineData("7.5 % 2", "1.5")]
    [InlineData("1 / 0", "undefined")]
    [InlineData("5 % 0", "undefined")]
    [InlineData("0.1 + 0.2", "0.30000000000000004")]
    [InlineData("1e300 * 1e300", "undefined")]
    [InlineData("'a' + 'b'", "undefined")]
    [InlineData("'1' + 1", "undefined")]
    [InlineData("null + 1", "undefined")]
    [InlineData("true + 1", "undefined")]
    [InlineData("undefined + 1", "undefined")]
    [InlineData("'a' || 'b'", "\"ab\"")]
    [InlineData("'a' || 'b' || 'c'", "\"abc\"")]
    [InlineData("1 || 'b'", "undefined")]
    [InlineData("-(3)", "-3")]
    [InlineData("-'a'", "undefined")]
    [InlineData("+5", "5")]
    [InlineData("+'a'", "undefined")]
    [InlineData("6 & 3", "2")]
    [InlineData("6 | 3", "7")]
    [InlineData("6 ^ 3", "5")]
    [InlineData("~5", "-6")]
    [InlineData("1 << 4", "16")]
    [InlineData("-16 >> 2", "-4")]
    [InlineData("-1 >>> 60", "15")]
    [InlineData("5.7 | 0", "5")]
    [InlineData("'a' | 1", "undefined")]
    public void Arithmetic(string expression, string expected) => Assert.Equal(expected, T.Eval(expression));

    [Theory]
    [InlineData("1 + 2 * 3", "7")]
    [InlineData("(1 + 2) * 3", "9")]
    [InlineData("10 - 4 - 3", "3")]
    [InlineData("2 * 3 % 4", "2")]
    [InlineData("1 + 2 = 3", "true")]
    [InlineData("2 | 1 = 3", "true")]
    [InlineData("1 << 2 + 1", "8")]
    [InlineData("NOT 1 = 2", "true")]
    [InlineData("1 < 2 AND 2 < 3", "true")]
    [InlineData("false AND false OR true", "true")]
    [InlineData("true OR false AND false", "true")]
    [InlineData("true ? 1 : 2", "1")]
    [InlineData("1 ? 1 : 2", "2")]
    [InlineData("undefined ? 1 : 2", "2")]
    [InlineData("false ? 1 : true ? 2 : 3", "2")]
    [InlineData("1 = 1 ? 'yes' : 'no'", "\"yes\"")]
    [InlineData("undefined ?? 1", "1")]
    [InlineData("null ?? 1", "null")]
    [InlineData("1 ?? 2", "1")]
    [InlineData("undefined ?? undefined ?? 3", "3")]
    [InlineData("undefined ?? 1 = 1", "true")]
    [InlineData("[1, 2][1]", "2")]
    [InlineData("{'a': {'b': 5}}.a.b", "5")]
    [InlineData("{'a': {'b': 5}}['a']['b']", "5")]
    [InlineData("[1, 2][5]", "undefined")]
    [InlineData("[1, 2][-1]", "undefined")]
    [InlineData("[1, 2][0.5]", "undefined")]
    [InlineData("[1, 2]['0']", "undefined")]
    [InlineData("{'a': 1}[0]", "undefined")]
    [InlineData("'abc'.length", "undefined")]
    [InlineData("'abc'[0]", "undefined")]
    public void PrecedenceAndAccess(string expression, string expected) => Assert.Equal(expected, T.Eval(expression));

    [Theory]
    [InlineData("[1, undefined, 2]", "[1,2]")]
    [InlineData("{'a': undefined, 'b': 1}", "{\"b\":1}")]
    [InlineData("[{'a': undefined}]", "[{}]")]
    [InlineData("[undefined]", "[]")]
    public void UndefinedIsOmittedFromConstructedValues(string expression, string expected) =>
        Assert.Equal(expected, T.Eval(expression));

    [Fact]
    public void UndefinedMembersFromDocumentsAreOmitted() =>
        Assert.Equal("""[[1,2],{"b":1}]""", T.Run("SELECT VALUE c.id = '1' ? [1, c.missing, 2] : {'a': c.missing, 'b': 1} FROM c WHERE c.id IN ('1', '2')"));

    [Fact]
    public void CoalesceBindsLooserThanComparison() =>
        // c.name ?? ('none' = 'none'): true only where name is undefined.
        Assert.Equal(T.J("['4']"), T.Run("SELECT VALUE c.id FROM c WHERE c.name ?? 'none' = 'none'"));

    [Fact]
    public void CoalesceKeepsNull() =>
        Assert.Equal(T.J("['none',null]"), T.Run("SELECT VALUE (c.name ?? 'none') FROM c WHERE c.id IN ('4', '5')"));

    [Fact]
    public void ParameterIndexing() =>
        Assert.Equal(T.J("[['y','Alice']]"), T.Run("SELECT VALUE [c.tags[@i], c[@p]] FROM c WHERE c.id = '1'", """{"@i":1,"@p":"name"}"""));
}
